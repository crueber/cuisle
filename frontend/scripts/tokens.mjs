// design/tokens.json → src/styles/tokens.css + src/styles/tokens.ts (architecture §4.7). Implementation: WP-10.
// Exported for tests: buildTokens(json) → { css, ts }; the CLI writes the files and exits non-zero on a light/dark key
// mismatch. Run from frontend/: node scripts/tokens.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const HEADER = "GENERATED by scripts/tokens.mjs from design/tokens.json. Do not edit.";
const LARGE_SCALE = "1.25";
const NUMERIC = /^(-?\d+(?:\.\d+)?)(px|ms)?$/;

/** Throws when the light and dark colour trees do not have identical key sets ($-keys are ignored). */
function assertSameKeys(light, dark, path) {
  const keys = (n) => Object.keys(n).filter((k) => !k.startsWith("$"));
  const lk = new Set(keys(light));
  const dk = new Set(keys(dark));
  for (const k of lk) {
    if (!dk.has(k)) throw new Error(`tokens: color.dark is missing "${[...path, k].join(".")}" (present in light)`);
  }
  for (const k of dk) {
    if (!lk.has(k)) throw new Error(`tokens: color.light is missing "${[...path, k].join(".")}" (present in dark)`);
  }
  for (const k of lk) {
    const l = light[k];
    const d = dark[k];
    if (isGroup(l) || isGroup(d)) {
      if (!isGroup(l) || !isGroup(d)) throw new Error(`tokens: "${[...path, k].join(".")}" is a value in one mode and a group in the other`);
      assertSameKeys(l, d, [...path, k]);
    }
  }
}

const isGroup = (v) => v !== null && typeof v === "object";

/** Appends [name, value] pairs for every leaf; `$`-keys are skipped at any depth. */
function flatten(node, path, out) {
  for (const [k, v] of Object.entries(node)) {
    if (k.startsWith("$")) continue;
    if (isGroup(v)) flatten(v, [...path, k], out);
    else out.push([`--${[...path, k].join("-")}`, String(v)]);
  }
  return out;
}

/** Converts a group to numeric mirrors: "46px" and "80ms" become numbers, `$`-keys are skipped. */
function numeric(node) {
  const out = {};
  for (const [k, v] of Object.entries(node)) {
    if (k.startsWith("$")) continue;
    if (isGroup(v)) out[k] = numeric(v);
    else {
      const m = NUMERIC.exec(String(v));
      out[k] = m ? Number(m[1]) : String(v);
    }
  }
  return out;
}

const decls = (pairs) => pairs.map(([name, value]) => `  ${name}: ${value};`).join("\n");

/**
 * Builds the CSS and TS outputs from a parsed tokens.json. Does not mutate its input.
 * @returns {{ css: string, ts: string }}
 */
export function buildTokens(json) {
  const { color, ...rest } = json;
  if (!color || !color.light || !color.dark) throw new Error("tokens: color.light and color.dark are required");
  assertSameKeys(color.light, color.dark, ["color"]);

  const root = [];
  for (const [k, v] of Object.entries(rest)) {
    if (k.startsWith("$")) continue;
    if (isGroup(v)) flatten(v, [k], root);
    else root.push([`--${k}`, String(v)]);
  }
  flatten(color.light, ["color"], root);
  const dark = flatten(color.dark, ["color"], []);

  const css = [
    `/* ${HEADER} */`,
    ":root {",
    decls([...root, ["--text-scale", "1"], ["--zoom", "1"], ["--scale", "var(--text-scale)"]]),
    "}",
    ':root[data-theme="dark"] {',
    decls(dark),
    "}",
    ':root[data-text="large"] {',
    `  --text-scale: ${LARGE_SCALE};`,
    "}",
    "",
  ].join("\n");

  const pick = (k) => `export const ${k} = ${JSON.stringify(numeric(rest[k]), null, 2)};`;
  const ts = [
    `// ${HEADER}`,
    "// Numeric mirrors of design/tokens.json for layout/ and state/ (CSS custom properties cannot be compared in JS).",
    "",
    pick("breakpoint"),
    "",
    pick("motion"),
    "",
    pick("size"),
    "",
  ].join("\n");

  return { css, ts };
}

// CLI: only when this file is the entry point, so importing it (tests) has no side effects.
if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const here = dirname(fileURLToPath(import.meta.url));
  try {
    const json = JSON.parse(readFileSync(resolve(here, "..", "..", "design", "tokens.json"), "utf8"));
    const { css, ts } = buildTokens(json);
    writeFileSync(resolve(here, "..", "src", "styles", "tokens.css"), css);
    writeFileSync(resolve(here, "..", "src", "styles", "tokens.ts"), ts);
  } catch (err) {
    console.error(err instanceof Error ? err.message : err);
    process.exitCode = 1;
  }
}
